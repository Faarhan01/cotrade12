"""Ports (Protocols) for the Cotrade application layer.

Modules in `core.application` and the HTTP/CLI transports depend on these
interfaces, never on the concrete MT5 engine or SQLite store. Concrete
adapters live in `gateway/cony/adapter.py` (MT5 side) and
`database/repositories.py` (persistence side).
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Protocol

from knowledgebase.patterns import Bar
from knowledgebase.strategies import Strategy


class MarketDataPort(Protocol):
    def instrument(self, symbol: str) -> Dict[str, Any]: ...
    def candles(
        self,
        symbol: str,
        timeframe: str,
        count: int,
        days: Optional[int] = None,
    ) -> List[Bar]: ...


class MT5Port(Protocol):
    def is_connected(self) -> bool: ...
    def connection_info(self) -> Dict[str, Any]: ...
    def clock_offset(self) -> Optional[float]: ...
    def get_symbol_info(self, symbol: str) -> Dict[str, Any]: ...


class AccountPort(Protocol):
    def account_info(self) -> Dict[str, Any]: ...
    def get_positions(self, **kw: Any) -> List[Dict[str, Any]]: ...
    def get_orders(self, **kw: Any) -> List[Dict[str, Any]]: ...
    def get_totals(self) -> Dict[str, Any]: ...


class TradingPort(Protocol):
    def check_order(self, request: Dict[str, Any]) -> Dict[str, Any]: ...
    def send_order(self, request: Dict[str, Any]) -> Dict[str, Any]: ...
    def close_position(self, ticket: int, **kw: Any) -> Dict[str, Any]: ...
    def modify_position(self, ticket: int, **kw: Any) -> Dict[str, Any]: ...
    def calc_size(
        self, symbol: str, risk_amount: float, stop_pips: float
    ) -> Dict[str, Any]: ...


class StrategyRepository(Protocol):
    def load(self, name: str) -> Optional[Strategy]: ...
    def save(self, strategy: Strategy) -> int: ...
    def list(self) -> List[Dict[str, Any]]: ...
    def delete(self, name: str) -> bool: ...


class ReportRepository(Protocol):
    def save(self, report: Dict[str, Any]) -> int: ...
    def list(
        self,
        *,
        strategy: Optional[str] = None,
        verdict: Optional[str] = None,
        limit: int = 100,
    ) -> List[Dict[str, Any]]: ...
    def best(self, limit: int = 20) -> List[Dict[str, Any]]: ...


class PatternHitRepository(Protocol):
    def save_hits(
        self,
        run_id: str,
        symbol: str,
        timeframe: str,
        hits: List[Dict[str, Any]],
    ) -> int: ...
    def query(
        self,
        pattern: Optional[str] = None,
        symbol: Optional[str] = None,
        limit: int = 500,
    ) -> List[Dict[str, Any]]: ...
    def frequency(
        self, symbol: Optional[str] = None
    ) -> List[Dict[str, Any]]: ...


class ConnectionPort(Protocol):
    def connect(self, **kw: Any) -> Dict[str, Any]: ...
    def disconnect(self) -> None: ...
    def start_auto_reconnect(self, interval_seconds: int = 20) -> None: ...
